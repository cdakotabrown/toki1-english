#!/usr/bin/env python3
"""Build the stand-alone English patcher: one program that carries
english.ppf, checks the player's Track 1 by SHA-1 and writes the English
disc beside it (tools/patch/patcher.c).

    python3 tools/patch/make_patcher.py [--ppf build/patch/english.ppf]
        [--out build/patcher] [--mingw PREFIX] [--no-test]

Outputs: OUT/"Tokimeki Memorial English Patch.exe" (Windows, when a MinGW
x86_64 compiler is found: on PATH, or PREFIX such as
../toki1-pc/build/mingw-root/usr/bin/) and OUT/tokimeki-english-patch
(this machine).  The checksums the program checks come from the files on
this machine: the player's Track 1 and the result of applying the PPF to
it.  The test runs the native program on a copy of the disc directory and
requires the result to be the built English Track 1.

The program holds the PPF and nothing else of the disc: see
tools/patch/package_ppf.py for what a PPF contains.
"""
import argparse
import hashlib
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from roots import ROOT, DECOMP  # noqa: E402

TRACK1 = "Tokimeki Memorial - Forever with You (Japan) (Rev 1) (Track 1).bin"
TRACK2 = "Tokimeki Memorial - Forever with You (Japan) (Rev 1) (Track 2).bin"
CUE = "Tokimeki Memorial - Forever with You (Japan) (Rev 1).cue"
OUT_BIN = "Tokimeki Memorial - Forever with You (English) (Track 1).bin"
OUT_CUE = "Tokimeki Memorial - Forever with You (English).cue"
WIN_NAME = "Tokimeki Memorial English Patch.exe"
SRC = Path(__file__).resolve().parent / "patcher.c"


def sha1_file(path, patch=None):
    """SHA-1 of a file, with the PPF records laid over it when given."""
    data = bytearray(Path(path).read_bytes())
    for off, run in patch or ():
        data[off:off + len(run)] = run
    return hashlib.sha1(data).hexdigest(), len(data)


def ppf_records(ppf):
    raw = Path(ppf).read_bytes()
    if raw[:5] != b"PPF30" or raw[0x38:0x3B] != b"\0\0\0":
        raise SystemExit(f"{ppf}: not a plain PPF 3.0 (no block check, no undo)")
    pos, out = 60, []
    while pos + 9 <= len(raw):
        off, n = struct.unpack_from("<QB", raw, pos)
        out.append((off, raw[pos + 9:pos + 9 + n]))
        pos += 9 + n
    if pos != len(raw):
        raise SystemExit(f"{ppf}: trailing bytes after the last record")
    return out


def mingw(prefix):
    names = ["x86_64-w64-mingw32-gcc-posix", "x86_64-w64-mingw32-gcc"]
    for d in ([prefix] if prefix else []) + [None]:
        for n in names:
            exe = shutil.which(n) if d is None else (str(Path(d) / n) if (Path(d) / n).exists() else None)
            if exe:
                return exe
    return None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ppf", default=str(ROOT / "build/patch/english.ppf"))
    ap.add_argument("--disks", default=str(DECOMP / "disks"))
    ap.add_argument("--out", default=str(ROOT / "build/patcher"))
    ap.add_argument("--mingw", help="directory that holds x86_64-w64-mingw32-gcc")
    ap.add_argument("--no-test", action="store_true")
    a = ap.parse_args(argv)

    ppf, disks, out = Path(a.ppf).resolve(), Path(a.disks), Path(a.out)
    track1 = disks / TRACK1
    if not ppf.exists() or not track1.exists():
        raise SystemExit(f"needs {ppf} (make patch) and {track1}")
    records = ppf_records(ppf)
    orig_sha, size = sha1_file(track1)
    result_sha, _ = sha1_file(track1, records)
    out.mkdir(parents=True, exist_ok=True)
    (out / "patcher_gen.h").write_text(
        "/* generated by tools/patch/make_patcher.py */\n"
        f"#define TRACK1_SIZE {size}LL\n#define TRACK1_SHA1 \"{orig_sha}\"\n"
        f"#define RESULT_SHA1 \"{result_sha}\"\n#define PPF_PATH \"{ppf}\"\n")
    flags = ["-O2", "-s", "-Wall", "-I", str(out)]
    native = out / "tokimeki-english-patch"
    subprocess.run(["cc", "-D_FILE_OFFSET_BITS=64", *flags, str(SRC), "-o", str(native)], check=True)
    print(f"patcher: {native}")
    cc = mingw(a.mingw)
    if cc:
        win = out / WIN_NAME
        subprocess.run([cc, "-municode", "-static", *flags, str(SRC), "-o", str(win)], check=True)
        print(f"patcher: {win} ({win.stat().st_size:,} bytes)")
    else:
        print("patcher: no MinGW compiler found (--mingw DIR): the Windows program was not built")
    print(f"patcher: applies to Track 1 {orig_sha}, result {result_sha}, {len(records):,} records")

    if a.no_test:
        return 0
    with tempfile.TemporaryDirectory(prefix="patcher-test-", dir=out) as tmp:
        tmp = Path(tmp)
        for name in (TRACK1, TRACK2, CUE):
            if (disks / name).exists():
                os.symlink((disks / name).resolve(), tmp / name)
        r = subprocess.run([str(native), str(tmp / CUE)], capture_output=True, text=True)
        got = sha1_file(tmp / OUT_BIN)[0] if (tmp / OUT_BIN).exists() else None
        cue = (tmp / OUT_CUE).read_text() if (tmp / OUT_CUE).exists() else ""
        if r.returncode or got != result_sha or OUT_BIN not in cue or TRACK2 not in cue:
            print(r.stdout[-1500:], r.stderr[-500:])
            raise SystemExit("patcher: TEST FAILED")
        # the wrong disc is refused and leaves nothing behind
        bad = tmp / "bad"
        bad.mkdir()
        data = bytearray((disks / TRACK1).read_bytes())
        data[0x9000] ^= 1
        (bad / TRACK1).write_bytes(data)
        r2 = subprocess.run([str(native), str(bad / TRACK1)], capture_output=True, text=True)
        if r2.returncode == 0 or (bad / OUT_BIN).exists() or "not the disc" not in r2.stdout:
            print(r2.stdout[-1500:])
            raise SystemExit("patcher: NEGATIVE TEST FAILED (a changed disc was accepted)")
        built = ROOT / "build/patch/iso/patched_disc.bin"
        if built.exists():
            with open(built, "rb") as f:
                if hashlib.sha1(f.read(size)).hexdigest() != result_sha:
                    raise SystemExit("patcher: the result differs from the built English disc")
    print("patcher: test OK (result equals the built English Track 1; a changed disc is refused)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
