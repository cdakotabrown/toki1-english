#!/usr/bin/env python3
"""sync_patch_symbols.py - bring the English patch's references up to the
naming ledger's CURRENT names (src/patch/, config/patch/).

The naming track's landers rename the tokens they know about; the patch side
also names symbols and files in places they do not reach.  This tool reads
config/symbol_names.json and rewrites, in the patch tree only:

  C / headers   src/patch/**/*.c|h: every whole-word token that is a FORMER
                landed name (a `history` entry of a record) becomes the
                record's current spelling.  Address-form tokens
                (func_/D_XXXXXXXX) are valid forever and are left alone;
                --name-addresses also renames the main-scope ones whose
                address has a landed name (what the landers do; main scope
                only: an overlay-range address in main-module C has no
                overlay to name it by).  Names the patch itself DEFINES are
                never touched (the module's own `load_string` is not
                retail's).
  profiles      config/patch/*.json with "main" / "overlays": the
                documentary hook names (main.module.hooks[].function and
                overlays.<OV>.hooks[].function, by the hook's `addr`), the
                `expect` callee of a call-site redirect and a poke's
                `symbol` / `u32_symbol` when they are ledger names.  A hook
                whose name changes must carry an explicit `target`.
  compositions  config/patch/compositions.json: compositions[].src and the
                `waive` keys, C file paths named after their function, follow
                the function to its current file.
  free regions  config/patch/free_regions.json: regions[].functions.
  symbol map    config/patch/symbols.json "symbols": the name -> address map
                of every ledger name the patch C references, generated here
                (the build checks that a name still resolves to the address
                recorded there, so a name the ledger MOVES fails loudly
                instead of relinking; pc/tools/gen_lang_hooks.py reads it).
                "pins" (names the ledger has never known, each with a
                reason) are kept as they are.

JSON is edited as text (exact quoted literals only; every file is re-parsed
and compared with the intended structure), so formatting and key order are
kept.  Idempotent: a second --apply changes nothing.

  sync_patch_symbols.py --dry-run    print what would change (exit 0)
  sync_patch_symbols.py --check      exit 1 if anything would change
  sync_patch_symbols.py --apply      write the changes
  [--root DIR]                       another tree (the tests)
  [--decomp DIR]                     its ledger/C tree (default: --root when
                                     given, else toki1-decomp, tools/repo_paths.py)
"""
import argparse
import copy
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from roots import english_rel  # noqa: E402  (the patch tree in either layout)
import patch_symbols as PS  # noqa: E402

TOKEN_RE = re.compile(r"\b[A-Za-z_]\w*\b")
# one pass, left to right: a "//" inside a string is not a comment, and a
# quote inside a comment is not a string
LEXEME_RE = re.compile(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])+\'', re.S)
MAP_COMMENT = (
    "GENERATED by tools/patch/sync_patch_symbols.py --apply; do not edit "
    "\"symbols\" by hand.  \"symbols\": every naming-ledger name "
    "(config/symbol_names.json) the patch C references, with the address it "
    "resolved to when the map was written.  build_patched.py resolves names "
    "through the ledger (address-form func_/D_ names by their suffix) and "
    "FAILS when a name is a former one (old name, address and new name are "
    "printed), unknown, or resolves to another address than the one recorded "
    "here.  \"pins\": hand-kept names the ledger has never known, each with "
    "its \"addr\" and a \"reason\"; anything else does not belong there.")


def strip_c(text: str) -> str:
    """the C without comments, string / character literals and preprocessor
    lines (a '}' literal must not end a function body)"""
    text = LEXEME_RE.sub(lambda m: " " if m.group(0)[0] == "/" else '""', text)
    return "\n".join("" if ln.lstrip().startswith("#") else ln
                     for ln in text.splitlines())


def outside_literals(text: str, fn, blank: bool = False) -> str:
    """apply fn to every piece of `text` that is code or a comment, never to
    a string or character literal (blank=True drops the literals)"""
    out, pos = [], 0
    for m in LEXEME_RE.finditer(text):
        out.append(fn(text[pos:m.start()]))
        lex = m.group(0)
        if lex[0] == "/":
            out.append(fn(lex))
        else:
            out.append('""' if blank else lex)
        pos = m.end()
    out.append(fn(text[pos:]))
    return "".join(out)


def defined_names(code: str) -> set:
    """file-scope names a C file DEFINES (functions with a body, objects
    declared without `extern`); `code` is strip_c output"""
    out = set()
    depth = 0
    chunk = []
    i, n = 0, len(code)
    while i < n:
        c = code[i]
        if c == "{":
            if depth == 0:
                head = "".join(chunk)
                if re.search(r"\)\s*$", head) and not head.lstrip().startswith(
                        ("extern", "typedef")):
                    m = re.search(r"([A-Za-z_]\w*)\s*\([^()]*\)\s*$", head)
                    if m:
                        out.add(m.group(1))
                    chunk = []
                    # skip the function body
                    d = 0
                    while i < n:
                        if code[i] == "{":
                            d += 1
                        elif code[i] == "}":
                            d -= 1
                            if d == 0:
                                break
                        i += 1
                    i += 1
                    continue
            depth += 1
        elif c == "}":
            depth -= 1
        elif c == ";" and depth == 0:
            decl = "".join(chunk).strip()
            chunk = []
            i += 1
            if not decl or decl.startswith(("extern", "typedef")):
                continue
            body = re.sub(r"\{.*\}", " ", decl, flags=re.S)
            if re.search(r"\(\s*[^*)]", body.split("=")[0]) and "=" not in body:
                continue            # a prototype
            for part in re.split(r",(?![^()\[\]]*[)\]])", body.split("=")[0]):
                m = re.search(r"([A-Za-z_]\w*)\s*(?:\[[^\]]*\]\s*)*$", part.strip())
                if m:
                    out.add(m.group(1))
            continue
        chunk.append(c)
        i += 1
    return out


def leaves(obj, path=()):
    """the (path, value) pairs of a parsed JSON document (keys are part of
    the path, so a renamed key changes every leaf below it)"""
    out = set()
    if isinstance(obj, dict):
        for k, v in obj.items():
            out |= leaves(v, path + (("k", k),))
        if not obj:
            out.add((path, "{}"))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            out |= leaves(v, path + (("i", i),))
        if not obj:
            out.add((path, "[]"))
    else:
        out.add((path, json.dumps(obj)))
    return out


class Sync:
    def __init__(self, root: Path, name_addresses: bool = False,
                 decomp: Path = None):
        self.root = Path(root)              # the patch tree (src/patch, config/patch)
        self.decomp = Path(decomp) if decomp else self.root   # ledger + C tree
        self.name_addresses = name_addresses
        self.L = PS.Ledger(self.decomp / "config" / "symbol_names.json",
                           self.root / english_rel("config/patch", self.root) / "symbols.json")
        self.changes = []           # (file, what)
        self.errors = []
        self.writes = {}            # path -> new text
        self.defined = set()        # names src/patch itself defines

    def rel(self, p: Path) -> str:
        return str(p.relative_to(self.root))

    # -- C ------------------------------------------------------------------
    def c_files(self):
        base = self.root / english_rel("src/patch", self.root)
        return sorted(p for p in base.rglob("*") if p.suffix in (".c", ".h")) \
            if base.exists() else []

    def c_rename_map(self, files):
        defined = set()
        for p in files:
            defined |= defined_names(strip_c(p.read_text(errors="replace")))
        self.defined = defined
        ren = {}
        for p in files:
            text = outside_literals(p.read_text(errors="replace"), lambda s: s,
                                    blank=True)
            for tok in set(TOKEN_RE.findall(text)):
                if tok in ren or tok in defined:
                    continue
                r = self.L.resolve(tok, "main")
                if r.status in ("renamed", "reverted"):
                    ren[tok] = r.name
                elif self.name_addresses and r.status == "address-form" \
                        and r.addr < 0x80132000:
                    nm = self.L.landed_at(r.addr, "main")
                    if nm and nm != tok:
                        ren[tok] = nm
        clash = sorted(t for t, new in ren.items() if new in defined)
        for t in clash:
            self.errors.append(f"src/patch: `{t}` would become `{ren[t]}`, which the "
                               f"patch itself defines; rename the patch's own symbol first")
            del ren[t]
        return ren

    def sync_c(self):
        files = self.c_files()
        ren = self.c_rename_map(files)
        if not ren:
            return
        pat = re.compile(r"\b(" + "|".join(map(re.escape, sorted(ren, key=len, reverse=True)))
                         + r")\b")
        for p in files:
            t = p.read_text(errors="replace")
            hits = {}

            def sub(m):
                hits[m.group(1)] = hits.get(m.group(1), 0) + 1
                return ren[m.group(1)]
            nt = outside_literals(t, lambda seg: pat.sub(sub, seg))
            if nt != t:
                self.writes[p] = nt
                for old, k in sorted(hits.items()):
                    self.changes.append((self.rel(p), f"{old} -> {ren[old]} ({k}x)"))

    # -- JSON ---------------------------------------------------------------
    def edit_json(self, p: Path, mutate):
        """mutate(obj) returns [(old, new, what)] string-literal replacements
        it applied to obj; the file is edited as text and must re-parse to
        exactly the mutated obj"""
        text = self.writes.get(p, p.read_text())
        obj = json.loads(text)
        want = copy.deepcopy(obj)
        reps = mutate(want)
        if not reps:
            return
        # replace the quoted literals ONE OCCURRENCE at a time, keeping only
        # the replacements that bring the parse closer to the intended
        # structure (the same literal may also stand where it must stay,
        # e.g. a hook's "target" equal to its old "function")
        nt = text
        goal = leaves(want)
        for old, new in sorted({(o, n) for o, n, _ in reps}):
            for lit_o, lit_n in ((json.dumps(old), json.dumps(new)),
                                 (json.dumps(old, ensure_ascii=False),
                                  json.dumps(new, ensure_ascii=False))):
                pos = 0
                while True:
                    i = nt.find(lit_o, pos)
                    if i < 0:
                        break
                    trial = nt[:i] + lit_n + nt[i + len(lit_o):]
                    if len(leaves(json.loads(trial)) ^ goal) < len(leaves(json.loads(nt)) ^ goal):
                        nt = trial
                        pos = i + len(lit_n)
                    else:
                        pos = i + len(lit_o)
        if json.loads(nt) != want:
            self.errors.append(f"{self.rel(p)}: a textual edit would change more than "
                               f"the intended references ({', '.join(o for o, _, _ in reps)}); "
                               f"edit it by hand")
            return
        self.writes[p] = nt
        for old, new, what in reps:
            self.changes.append((self.rel(p), f"{what}: {old} -> {new}"))

    def sync_profiles(self):
        for p in sorted((self.root / english_rel("config/patch", self.root)).glob("*.json")):
            try:
                obj = json.loads(p.read_text())
            except ValueError:
                continue
            if not isinstance(obj, dict) or not ({"main", "overlays"} & set(obj)):
                continue

            def mutate(o, p=p):
                reps = []
                main = o.get("main", {}) or {}
                hooks = [("main", h) for h in (main.get("module", {}) or {}).get("hooks", [])]
                for ov, spec in (o.get("overlays", {}) or {}).items():
                    hooks += [(ov, h) for h in (spec or {}).get("hooks", [])]
                for scope, h in hooks:
                    if "addr" not in h or "function" not in h:
                        continue
                    a = int(str(h["addr"]), 16)
                    key = self.L.func_at(a, scope)
                    if key is None:
                        continue
                    cur = self.L.name_at(key, scope, "func")
                    if cur and cur != h["function"]:
                        if "target" not in h:
                            self.errors.append(
                                f"{self.rel(p)}: hook {h['function']} (0x{a:08X}) is now "
                                f"`{cur}` but has no explicit \"target\" (the module "
                                f"function it jumps to); add one, then sync")
                            continue
                        reps.append((h["function"], cur, f"{scope} hook 0x{a:08X}"))
                        h["function"] = cur
                cs_lists = [("main", main.get("callsites", []))] + \
                    [(ov, (spec or {}).get("callsites", []))
                     for ov, spec in (o.get("overlays", {}) or {}).items()]
                for scope, lst in cs_lists:
                    for cs in lst:
                        e = cs.get("expect")
                        if isinstance(e, str) and not e.startswith("0x"):
                            r = self.L.resolve(e, "main")
                            if r.status in ("renamed", "reverted"):
                                reps.append((e, r.name, f"{scope} callsite {cs.get('at')}"))
                                cs["expect"] = r.name
                for pk in main.get("pokes", []):
                    for fld in ("symbol", "u32_symbol"):
                        v = pk.get(fld)
                        if isinstance(v, str) and v not in self.defined:
                            r = self.L.resolve(v, "main")
                            if r.status in ("renamed", "reverted"):
                                reps.append((v, r.name, f"poke {fld}"))
                                pk[fld] = r.name
                return reps
            self.edit_json(p, mutate)

    def sync_compositions(self):
        p = self.root / english_rel("config/patch", self.root) / "compositions.json"
        if not p.exists():
            return

        def fix(path, what):
            if (self.decomp / path).exists():
                return None
            new = self.L.current_path(path)
            if new and new != path and (self.decomp / new).exists():
                return new
            return None

        def mutate(o):
            reps = []
            for c in o.get("compositions", []):
                new = fix(c.get("src", ""), "src")
                if new:
                    reps.append((c["src"], new, f"composition {c.get('id')} src"))
                    c["src"] = new
            for d in o.get("draw_slots", []):
                for i, s in enumerate(d.get("src", [])):
                    new = fix(s, "src")
                    if new:
                        reps.append((s, new, f"draw slot {d.get('ov')}:{d.get('s')} src"))
                        d["src"][i] = new
            waive = o.get("waive", {})
            for k in list(waive):
                new = fix(k, "waive")
                if new:
                    if new in waive:
                        self.errors.append(f"compositions.json: waive {k} and {new} "
                                           f"name the same function; merge them by hand")
                        continue
                    reps.append((k, new, "waive"))
            if reps:
                o["waive"] = {next((n for oo, n, w in reps if w == "waive" and oo == k), k): v
                              for k, v in waive.items()}
            return reps
        self.edit_json(p, mutate)

    def sync_free_regions(self):
        p = self.root / english_rel("config/patch", self.root) / "free_regions.json"
        if not p.exists():
            return

        def mutate(o):
            reps = []
            for r in o.get("regions", []):
                fs = r.get("functions", [])
                for i, f in enumerate(fs):
                    res = self.L.resolve(f, "main")
                    new = None
                    if res.status in ("renamed", "reverted"):
                        new = res.name
                    elif res.status == "address-form":
                        new = self.L.landed_at(res.addr, "main")
                    if new and new != f:
                        reps.append((f, new, f"free region {r.get('start')}"))
                        fs[i] = new
            return reps
        self.edit_json(p, mutate)

    # -- the generated map --------------------------------------------------
    def sync_map(self):
        p = self.root / english_rel("config/patch", self.root) / "symbols.json"
        old = json.loads(p.read_text()) if p.exists() else {}
        names = {}
        for f in self.c_files():
            text = self.writes.get(f) or f.read_text(errors="replace")
            for tok in set(TOKEN_RE.findall(strip_c(text))):
                if tok in self.defined or PS.address_form(tok) is not None:
                    continue
                r = self.L.resolve(tok, "main")
                if r.status == "current":
                    rec = self.L.records.get(("main", r.addr), {})
                    names[tok] = {"addr": f"0x{r.addr:08X}",
                                  "kind": rec.get("kind", "data")}
        prev = old.get("symbols", {})
        for nm, ent in names.items():
            was = prev.get(nm)
            if was and int(was["addr"], 16) != int(ent["addr"], 16):
                self.errors.append(
                    f"config/patch/symbols.json: `{nm}` was recorded at {was['addr']} and "
                    f"the ledger now puts it at {ent['addr']} (a moved name): check every "
                    f"patch use of it, then delete its entry from the map and sync again")
                names[nm] = was
        new = {"_comment": MAP_COMMENT,
               "symbols": dict(sorted(names.items())),
               "pins": old.get("pins", {})}
        for nm, pin in new["pins"].items():
            if not str(pin.get("reason", "")).strip():
                self.errors.append(f"config/patch/symbols.json: pin `{nm}` has no reason")
        text = json.dumps(new, indent=2) + "\n"
        if not p.exists() or p.read_text() != text:
            self.writes[p] = text
            gone = sorted(set(prev) - set(names))
            added = sorted(set(names) - set(prev))
            what = []
            if added:
                what.append(f"+{len(added)} ({' '.join(added[:12])}{' ...' if len(added) > 12 else ''})")
            if gone:
                what.append(f"-{len(gone)} ({' '.join(gone[:12])}{' ...' if len(gone) > 12 else ''})")
            self.changes.append((self.rel(p), "symbol map " + (", ".join(what) or "format")))

    def run(self):
        self.sync_c()
        self.sync_profiles()
        self.sync_compositions()
        self.sync_free_regions()
        self.sync_map()
        return self

    def apply(self):
        for p, t in self.writes.items():
            p.write_text(t)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--dry-run", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--apply", action="store_true")
    ap.add_argument("--name-addresses", action="store_true",
                    help="also rename address-form C tokens whose address has a landed name")
    ap.add_argument("--root", default=None)
    ap.add_argument("--decomp", default=None)
    a = ap.parse_args(argv)
    root = Path(a.root) if a.root else PS.ROOT
    decomp = Path(a.decomp) if a.decomp else (root if a.root else PS.DECOMP)
    s = Sync(root, a.name_addresses, decomp).run()
    for f, what in s.changes:
        print(f"{'renamed' if a.apply else 'would change'}  {f}: {what}")
    for e in s.errors:
        print(f"ERROR  {e}")
    if a.apply and not s.errors:
        s.apply()
    n = len(s.changes)
    print(f"[sync_patch_symbols] {n} change(s){' written' if a.apply and not s.errors and n else ''}"
          f", {len(s.errors)} error(s)")
    if s.errors:
        return 2
    if a.check and n:
        print(f"[sync_patch_symbols] the patch tree is behind the ledger; run "
              f"`{PS.SYNC_HINT}`")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
