def build_string_pool(profile: dict, dte=None):
    """Concatenate every relocated ("ptr_at") main string, NUL-terminated and
    4-aligned, in profile order (apply_main_strings() recomputes the same
    offsets when it writes the pointer words), then the DTE dictionary
    entries (plain ASCII + NUL, unaligned).  Returns (pool, dte_offsets)."""
    pool = bytearray()
    for s in main_string_entries(profile):
        if "ptr_at" not in s:
            continue
        enc = encode_text(s["text"], s.get("encoding", "patch"), bool(s.get("dte", False))) + b"\0"
        pool += enc + b"\0" * ((-len(enc)) % 4)
    dte_offsets = []
    for e in dte or []:
        if not e or any(not (0x20 <= ord(c) <= 0x7E) for c in e):
            raise SystemExit(f"[patch] DTE entry {e!r} is not plain ASCII")
        dte_offsets.append(len(pool))
        pool += e.encode("ascii") + b"\0"
    MODULE_OFFSETS.clear()
    for enc in MODULE_STRINGS:
        MODULE_OFFSETS.append(len(pool))
        pool += enc + b"\0"
    return bytes(pool), dte_offsets


def apply_containers(profile: dict, report: dict, verbose=False):
    """Run the sheet injector (tools/patch/inject.py) for the profile's
    `containers` section and return (files{CDROM/...: path}, dte_entries)."""
    spec = profile.get("containers")
    if not spec:
        return {}, []
    import inject
    dte_spec = spec.get("dte", "auto")
    dte_path = None
    if dte_spec not in ("auto", True, False, "none"):
        # a cached table (build/patch/gen/dte.json is a build product: a
        # fresh checkout rebuilds it from the sheets)
        dte_path = locate(dte_spec)
        if not dte_path.exists():
            print(f"[patch] DTE table {dte_spec} missing; building it")
            dte_path = None
        elif len(json.loads(dte_path.read_text())["entries"]) > textcodec.DTE_COUNT:
            print(f"[patch] DTE table {dte_spec} has more than "
                  f"{textcodec.DTE_COUNT} entries (stale); rebuilding it")
            dte_path = None
    files, dte, rep = inject.run(
        dirs=spec.get("dirs"), only=spec.get("only"),
        dte_path=dte_path,
        no_dte=(dte_spec in (False, "none")),
        accept=spec.get("status", list(inject.ACCEPT_STATUS)),
        trust_maxbytes=bool(spec.get("trust_maxbytes", False)),
        verbose=verbose, dte_count=int(spec.get("dte_count", textcodec.DTE_COUNT)),
        wide_choices=spec.get("wide_choices", "fail"))
    report["containers"] = {"report": "build/patch/inject.report.json",
                            "totals": rep["totals"],
                            "files": sorted(files)}
    return files, dte


