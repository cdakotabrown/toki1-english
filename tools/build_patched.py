class SymbolPins:
    """Rename-proof symbol resolution for the patch profile.

    The decompilation renames main-binary symbols (func_XXXXXXXX -> a landed name,
    or a landed name -> a better one) while this profile is being worked on.
    Every name the module, the hooks, the call-site redirects and the pokes
    reference is resolved to an ADDRESS through the naming ledger
    (tools/patch/patch_symbols.py over config/symbol_names.json):
    address-form names (func_/D_/jtbl_ + 8 hex digits) by their suffix, a
    landed name by its record.  A name the ledger used to give an address and
    no longer does fails the build with the old name, the address and the
    new name (`tools/patch/sync_patch_symbols.py --apply` rewrites the patch
    side); so does an unknown name, and a name that now resolves to another
    address than the one config/patch/symbols.json recorded for it (a moved
    name must never relink silently).  The "pins" of that file, each with a
    reason, cover names the ledger has never known.
    """

    def __init__(self, path: Path, pin_mode: bool = False, ledger_path: Path = None):
        import patch_symbols
        self.path = path
        self.pin_mode = pin_mode
        self.ledger = patch_symbols.Ledger(ledger_path or patch_symbols.LEDGER, path)
        self.map = {}
        if path.exists():
            self.map = json.loads(path.read_text()).get("symbols", {})
        self.missing = []           # problem messages
        self.drift = []
        self.unmapped = []          # resolved names the generated map lacks

    def live_name(self, addr: int, scope: str = "main"):
        return self.ledger.landed_at(addr, scope)

    def resolve(self, sym: str):
        r = self.ledger.resolve(sym, "main")
        if not r.ok:
            msg = r.message()
            if msg not in self.missing:
                self.missing.append(msg)
            return None
        if r.status == "current":
            want = self.map.get(sym)
            if want is not None and hx(want["addr"]) != r.addr:
                msg = (f"`{sym}` now resolves to 0x{r.addr:08X} in "
                       f"config/symbol_names.json, but the patch was built "
                       f"against {want['addr']} ({self.path.name}): the "
                       f"ledger MOVED the name; check every patch use, then "
                       f"drop its map entry and run `python3 "
                       f"tools/patch/sync_patch_symbols.py --apply`")
                if msg not in self.missing:
                    self.missing.append(msg)
                return None
            if want is None and sym not in self.unmapped:
                self.unmapped.append(sym)
        return r.addr

    def fail_if_missing(self, where: str):
        if self.missing:
            raise SystemExit(
                f"[patch] {where}: {len(self.missing)} symbol reference(s) do not "
                f"resolve:\n" + "\n".join(f"        {m}" for m in self.missing))

    def save(self):
        """the build never writes the map: sync_patch_symbols.py does"""

    def report_drift(self):
        if self.unmapped:
            print(f"[patch] note: {len(self.unmapped)} resolved name(s) are not in "
                  f"config/patch/{self.path.name} yet ({' '.join(sorted(self.unmapped)[:8])}"
                  f"{' ...' if len(self.unmapped) > 8 else ''}); run "
                  f"`python3 tools/patch/sync_patch_symbols.py --apply`")

