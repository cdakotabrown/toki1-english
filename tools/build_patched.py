def compile_override(src: Path, tmpdir: Path, verbose=False) -> Path:
    obj = tmpdir / (src.stem + ".o")
    cmd = [str(CC)] + ido_flags([DECOMP / "include"], src) + \
        ["-c", str(src), "-o", str(obj)]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0 or not obj.exists():
        raise SystemExit(f"[patch] IDO failed on {src}:\n{r.stderr[-800:]}")
    if verbose:
        print(f"  cc {' '.join(cmd[1:])}")
    return obj


def link_at(obj: Path, text_base: int, tmpdir: Path,
            extra_syms: dict, pins: SymbolPins, verbose=False):
    """Link obj's .text at text_base with every relocation symbol DEFINED at
    its PINNED address (config/patch/symbols.json) or, for an address-form
    name, at the address in the name; overridden by extra_syms (symbols this
    profile relocates).  Returns (text_bytes, resolved{name: addr})."""
    resolved = {}
    for _off, _ty, sym in get_reloc_symbols(obj):
        if sym in resolved or sym.startswith("."):
            continue
        a = extra_syms.get(sym)
        if a is None:
            a = pins.resolve(sym)
        if a is not None:
            resolved[sym] = a
    pins.fail_if_missing(obj.name)
    defs = "\n".join(f"  {s} = 0x{a:08X};" for s, a in sorted(resolved.items()))
    script = f"""OUTPUT_FORMAT("elf32-tradlittlemips")
OUTPUT_ARCH(mips)
SECTIONS {{
  .text 0x{text_base:08X} : SUBALIGN(4) {{ *(.text*) }}
{defs}
  /DISCARD/ : {{ *(.reginfo) *(.mdebug*) *(.comment) *(.pdr)
                *(.gnu.attributes) *(.MIPS.abiflags) *(.rodata*) *(.data*) *(.sdata*) *(.bss*) *(.sbss*) }}
}}
"""
    ld_path = tmpdir / "patch.ld"
    ld_path.write_text(script)
    elf = tmpdir / "patch.elf"
    r = subprocess.run([LD, "-T", str(ld_path), "-o", str(elf), str(obj),
                        "--no-warn-mismatch", "-e", "0"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"[patch] ld failed: {r.stderr[-800:]}")
    binp = tmpdir / "patch.bin"
    subprocess.run([OBJCOPY, "-O", "binary", "-j", ".text", str(elf),
                    str(binp)], check=True)
    return binp.read_bytes(), resolved


def section_sizes(obj: Path) -> dict:
    r = subprocess.run(["mipsel-linux-gnu-objdump", "-h", str(obj)],
                       capture_output=True, text=True)
    out = {}
    for line in r.stdout.splitlines():
        m = re.match(r"\s*\d+\s+(\.\S+)\s+([0-9a-f]+)", line)
        if m:
            out[m.group(1)] = int(m.group(2), 16)
    return out


def apply_main_overrides(profile: dict, exe: bytearray, report: dict,
                         pins: SymbolPins, verbose=False):
    """Compile each override, place it at `place_at`, and (mode=trampoline)
    write `j <func>; nop` into the retail window so every retail caller
    reaches the new body.  Returns the symbol map of relocated functions."""
    placed = {}
    for ov in profile.get("main", {}).get("overrides", []):
        src = locate(ov["source"])
        func = ov["function"]
        place_at = hx(ov["place_at"])
        retail_window = hx(ov["retail_window"])
        retail_size = int(ov["retail_size"])
        with tempfile.TemporaryDirectory() as td:
            tmp = Path(td)
            obj = compile_override(src, tmp, verbose)
            secs = section_sizes(obj)
            for s in (".rodata", ".data", ".sdata", ".bss", ".sbss"):
                if secs.get(s):
                    raise SystemExit(
                        f"[patch] {src.name}: override has a {s} section "
                        f"({secs[s]} bytes); the layout places .text only "
                        f"-- rewrite without static data (if-chain, not a "
                        f"switch table)")
            text_off = get_func_text_offset(obj, func)
            if text_off < THUNK_BYTES:
                raise SystemExit(f"[patch] {func}: unexpected .text offset "
                                 f"0x{text_off:X}")
            # .text base so that the first word AFTER the thunks lands at
            # place_at; the function symbol is then at place_at + (text_off
            # - THUNK_BYTES).
            text_base = place_at - THUNK_BYTES
            func_addr = place_at + (text_off - THUNK_BYTES)
            text, resolved = link_at(obj, text_base, tmp, placed, pins, verbose)
            body = text[THUNK_BYTES:]
        if len(body) % 4:
            body += b"\0" * (4 - len(body) % 4)
        lo, hi = file_off(place_at), file_off(place_at) + len(body)
        if hi > len(exe):
            raise SystemExit(f"[patch] {func}: placement 0x{place_at:08X}+"
                             f"{len(body)} runs past the image")
        clobbered = exe[lo:hi]
        exe[lo:hi] = body
        # trampoline in the retail window
        if ov.get("mode", "trampoline") == "trampoline":
            if retail_size < 8:
                raise SystemExit(f"[patch] {func}: window too small for j/nop")
            j_word = (2 << 26) | ((func_addr >> 2) & 0x3FFFFFF)
            w = file_off(retail_window)
            exe[w:w + 8] = struct.pack("<II", j_word, 0)
            # the rest of the dead retail body is left as is (harmless, and
            # keeps the patch small)
        placed[func] = func_addr
        entry = {
            "function": func, "source": rel(src),
            "placed_at": f"0x{place_at:08X}", "entry": f"0x{func_addr:08X}",
            "bytes": len(body), "retail_window": f"0x{retail_window:08X}",
            "retail_size": retail_size,
            "clobbered_range": f"0x{place_at:08X}-0x{place_at + len(body):08X}",
            "clobbered_was_zero": not any(clobbered),
            "clobbers_note": ov.get("clobbers", ""),
            "resolved_symbols": {k: f"0x{v:08X}" for k, v in sorted(resolved.items())},
        }
        report["main_overrides"].append(entry)
        print(f"[patch] main: {func} -> {len(body)} bytes at "
              f"0x{place_at:08X} (entry 0x{func_addr:08X}); trampoline at "
              f"0x{retail_window:08X}")
    return placed


