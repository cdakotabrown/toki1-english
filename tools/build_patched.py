def apply_main_strings(profile: dict, exe: bytearray, report: dict,
                       pool_base: int):
    entries = []
    off = 0
    for s in main_string_entries(profile):
        if s.get("module"):
            enc = module_ref_bytes(s)
        else:
            enc = encode_text(s["text"], s.get("encoding", "patch"), bool(s.get("dte", False)))
        if "ptr_at" in s:
            ptr_at = hx(s["ptr_at"])
            addr = pool_base + off
            old = struct.unpack_from("<I", exe, file_off(ptr_at))[0]
            if not (TEXT_BASE <= old < 0x80200000):
                raise SystemExit(f"[patch] ptr_at 0x{ptr_at:08X} does not hold "
                                 f"a RAM pointer (0x{old:08X}); wrong address?")
            struct.pack_into("<I", exe, file_off(ptr_at), addr)
            off += len(enc) + 1
            off += (-off) % 4
            entries.append({"ptr_at": f"0x{ptr_at:08X}", "old_target":
                            f"0x{old:08X}", "new_target": f"0x{addr:08X}",
                            "bytes": len(enc), "text": s["text"]})
            print(f"[patch] main: *0x{ptr_at:08X} -> 0x{addr:08X} "
                  f"{s['text']!r}")
        else:
            addr = hx(s["addr"])
            max_bytes = int(s["max_bytes"])
            if len(enc) > max_bytes:
                raise SystemExit(f"[patch] main 0x{addr:08X}: '{s['text']}' is "
                                 f"{len(enc)} bytes, budget {max_bytes}")
            lo = file_off(addr)
            if exe[lo + max_bytes] != 0:
                raise SystemExit(f"[patch] main 0x{addr:08X}: byte after the "
                                 f"budget is not NUL -- budget wrong?")
            exe[lo:lo + max_bytes + 1] = enc + b"\0" * (max_bytes + 1 - len(enc))
            entries.append({"addr": f"0x{addr:08X}", "max_bytes": max_bytes,
                            "bytes": len(enc), "text": s["text"]})
            print(f"[patch] main: 0x{addr:08X} <- {s['text']!r} "
                  f"({len(enc)}/{max_bytes} bytes)")
    report["main_strings"] = entries


