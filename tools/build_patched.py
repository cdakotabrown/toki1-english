def materialise_staging_dir(staging: Path, d: Path, extracted: Path):
    """The clean builder's staging tree links whole DIRECTORIES
    (staging/CDROM/SERIFU -> assets/extracted_iso/CDROM/SERIFU).  Writing a
    patched file "into" such a directory would replace the ORIGINAL in the
    extracted ISO (it did, on 2026-10-08: 56 containers had to be restored
    from the dump).  Before touching a file under `d`, turn every symlinked
    directory on its path into a real directory of per-entry symlinks, so
    the write lands in build/ and nowhere else."""
    rel = d.relative_to(staging)
    cur = staging
    for part in rel.parts:
        cur = cur / part
        if cur.is_symlink():
            real = cur.resolve()
            if not real.is_dir():
                raise SystemExit(f"[patch] staging {cur} links to a file")
            src = extracted / cur.relative_to(staging)
            st = src.stat()
            cur.unlink()
            cur.mkdir()
            for entry in real.iterdir():
                (cur / entry.name).symlink_to(entry)
            os.utime(cur, (st.st_atime, st.st_mtime))
    # final guard: the directory itself must now live inside the staging tree
    if not str((staging / rel).resolve()).startswith(str(staging.resolve())):
        raise SystemExit(f"[patch] refusing to write through {staging / rel} "
                         f"(resolves outside the staging tree)")


def build_iso(exe_path: Path, exns: dict, out_dir: Path, report: dict,
              files: dict = None):
    import build_clean_iso as bci
    staging = out_dir / "iso" / "staging"
    bci.STAGING = staging
    bci.OUT_DIR = out_dir / "iso"
    (out_dir / "iso").mkdir(parents=True, exist_ok=True)
    # the clean builder's staging (symlinks, TR02.WAV regeneration, mtimes);
    # allow_original_exe because the verified clean exe is identical anyway
    prov = bci.stage(allow_original_exe=True)
    # override with the patched files, keeping the ORIGINAL mtimes so the
    # directory records (and the PPF) do not change for the wrong reason
    exedir = staging / "CDROM" / "EXEDIR"
    for ov, p in exns.items():
        target = exedir / f"{ov}.EXN"
        orig = bci.EXTRACTED / "CDROM" / "EXEDIR" / f"{ov}.EXN"
        st = orig.stat()
        target.unlink()
        shutil.copy(p, target)
        os.utime(target, (st.st_atime, st.st_mtime))
    for rel, p in (files or {}).items():
        target = staging / rel
        orig = bci.EXTRACTED / rel
        st = orig.stat()
        materialise_staging_dir(staging, target.parent, bci.EXTRACTED)
        if target.is_symlink() or target.exists():
            target.unlink()
        shutil.copy(p, target)
        os.utime(target, (st.st_atime, st.st_mtime))
    # a materialised directory's mtime changed with every copy: re-stamp it
    for rel in (files or {}):
        d = (staging / rel).parent
        while d != staging:
            s2 = (bci.EXTRACTED / d.relative_to(staging)).stat()
            os.utime(d, (s2.st_atime, s2.st_mtime))
            d = d.parent
    orig_exe = bci.EXTRACTED / "PSX.EXE"
    st = orig_exe.stat()
    (staging / "PSX.EXE").unlink()
    shutil.copy(exe_path, staging / "PSX.EXE")
    os.utime(staging / "PSX.EXE", (st.st_atime, st.st_mtime))
    for staged, orig in ((exedir, bci.EXTRACTED / "CDROM" / "EXEDIR"),
                         (staging / "CDROM", bci.EXTRACTED / "CDROM"),
                         (staging, bci.EXTRACTED)):
        s2 = orig.stat()
        os.utime(staged, (s2.st_atime, s2.st_mtime))
    built = bci.run_mkpsxiso()          # <out_dir>/iso/clean_disc.bin
    final = out_dir / "iso" / "patched_disc.bin"
    final_cue = out_dir / "iso" / "patched_disc.cue"
    shutil.move(built, final)
    cue = (out_dir / "iso" / "clean_disc.cue").read_text()
    final_cue.write_text(cue.replace("clean_disc.bin", "patched_disc.bin"))
    (out_dir / "iso" / "clean_disc.cue").unlink()
    rec = bci.reconcile(final, TRACK1)
    report["iso"] = {"out": str(final.relative_to(ROOT)),
                     "cue": str(final_cue.relative_to(ROOT)),
                     "staging_provenance": prov,
                     "metadata_reconciled": rec["reconciled"],
                     "sectors_refused_by_reconcile": len(rec["refused"])}
    return final


def sector_diff(built: Path, orig: Path):
    """Sectors of track 1 whose payload differs (the patched content)."""
    n = orig.stat().st_size // SEC
    diffs = []
    with open(built, "rb") as fb, open(orig, "rb") as fo:
        for s in range(n):
            a = fo.read(SEC)
            b = fb.read(SEC)
            if a != b:
                diffs.append(s)
        size_ok = fb.seek(0, 2) >= n * SEC
    return diffs, n, size_ok


def write_ppf3(orig: Path, built: Path, out: Path, description: str):
    """PPF 3.0 (the PS1-standard patch format; PPF-O-Matic / applyppf):
    'PPF30' + version 2 + method 0 + 50-byte description + imagetype(0=BIN)
    + blockcheck(0) + undo(0) + reserved; then records of u64 offset, u8
    length (<=255), data.  Diffs are computed over the RAW 2352-byte track
    image, so the patch applies to the user's own Track 1 .bin.

    The header is exactly 60 bytes: magic (5), method (1), description at
    0x06 (50), image type 0x38, blockcheck 0x39, undo 0x3A, dummy 0x3B;
    records start at 0x3C.  (Before 2026-10-09 an extra byte after the
    method shifted everything by one and two stray NULs preceded the
    records: build_patched's own reader agreed with the writer, but
    PPF-O-Matic / applyppf3 / the reference emulator read an image type of 0x20 and
    record offsets shifted by 16 bits, so the patch did not apply.
    tools/patch/verify_ppf.py is the independent check.)"""
    desc = description.encode("ascii", "replace")[:50].ljust(50, b" ")
    header = b"PPF30" + bytes([2]) + desc + bytes([0, 0, 0, 0])
    assert len(header) == 60
    records = []
    nrec = 0
    with open(orig, "rb") as fo, open(built, "rb") as fb:
        size = min(orig.stat().st_size, built.stat().st_size)
        pos = 0
        chunk = 1 << 20
        while pos < size:
            a = fo.read(min(chunk, size - pos))
            b = fb.read(min(chunk, size - pos))
            i = 0
            n = len(a)
            while i < n:
                if a[i] == b[i]:
                    i += 1
                    continue
                j = i
                while j < n and j - i < 255 and a[j] != b[j]:
                    j += 1
                records.append(struct.pack("<QB", pos + i, j - i) + b[i:j])
                nrec += 1
                i = j
            pos += n
    out.write_bytes(header + b"".join(records))
    return nrec


def apply_ppf3_check(orig: Path, ppf: Path, built: Path) -> bool:
    """Parse the PPF with the spec-written reader of tools/patch/verify_ppf.py
    (not this file's writer), apply it to the pristine Track 1 dump and
    require the result to equal the built image byte for byte."""
    import verify_ppf
    return verify_ppf.verify(ppf, orig, built, quiet=True)


def main():
    import argparse
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("profile")
