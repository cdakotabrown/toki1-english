#!/usr/bin/env python3
"""build_patched.py - the NON-RETAIL "patch profile" build (English patch R&D).

The retail profile (`make check-exn-all`, `make check-clean-main`,
`make clean-iso`) rebuilds the disc from source and REFUSES anything that is
not byte-identical to the user's dump.  A translation build is intentionally
different, so it needs its own profile that:

  * starts from the verified clean builds (so every byte that is NOT patched
    is still the honest source build, never a copy of retail code);
  * applies a PATCH PROFILE (config/patch/<name>.json): C overrides for the
    main binary compiled with the same IDO 5.2 and linked BY SYMBOL NAME at
    the address the profile assigns (a trampoline is left in the retail
    window when the override does not fit), plus string overrides in the
    overlays' data regions;
  * re-stamps the EXN checksum trailer, re-assembles the disc with mkpsxiso
    from the pristine layout.xml (every file keeps its sector count, so the
    1,355 hardcoded (sectors, LBA) loader triples stay valid), reconciles
    the three mkpsxiso-inexpressible metadata sectors exactly like the clean
    build does, and
  * emits a PPF3 patch against the user's Track 1 dump plus a JSON report.

Nothing here touches disks/ or the retail outputs; everything lands under
build/patch/ (gitignored).  No game data is written into the repo: the
profile carries only addresses, byte budgets and ENGLISH text.

Profile schema (config/patch/<name>.json):
  main.module     ONE multi-file C module (the English text engine): every
                  source is compiled with IDO, the objects are linked
                  together (.text .rodata .data .bss in that order) by name
                  at an address inside `region` ("place": "end" puts it at
                  the top of the region so the lowest kanji glyphs survive),
                  .bss is zeroed in the image, each `hooks[]` entry
                  {"function", "addr", ["target"]} gets a `j <module func>;
                  nop` trampoline in the retail window at `addr` (size by
                  address from config/symbol_names.json / level3_functions),
                  and `set` writes builder-computed values into named module
                  data symbols (e.g. patch_kanji_limit).
                  `extra_regions_file` (config/patch/free_regions.json):
                  more room for the module in retail code nothing can reach
                  (tools/patch/free_regions.py, re-checked at every build):
                  whole input sections (.text / .rodata / .data / .bss of
                  one object) are placed there biggest first and the linker
                  resolves every reference across regions; the rest stays
                  in `region`.  The build prints the main region's
                  HEADROOM (region - module - pool, what the kanji subset
                  gets) and warns below `headroom_warn` (default 2048).
  main.poison_regions_file  TEST builds only (english-poison.json): fill
                  the regions of that file with self-loop traps, the
                  runtime check behind extra_regions_file.
  symbols         (optional) the symbol MAP, default config/patch/symbols.json
                  (generated by tools/patch/sync_patch_symbols.py --apply):
                  every NAMED symbol the C / hooks / call sites / pokes use
                  resolves through the naming ledger config/symbol_names.json
                  (see SymbolPins); a former name, an unknown name or a name
                  the ledger has moved away from the mapped address fails
                  the build with the old name, the address and the new name.
  main.overrides  legacy single-function overrides (text only).
  main.strings    main-executable string overrides: {"addr", "max_bytes",
                  "text"} rewrites a string in place; {"ptr_at", "text"}
                  places the text in a STRING POOL directly below the module
                  (inside the same reclaimed region) and rewrites the pointer
                  word at ptr_at (for pointer tables such as the girl-name
                  table D_800B9AE0, whose Shift-JIS slots are too short for
                  English).  Encoding defaults to "patch".
  overlays.<OV>.strings   in-place string overrides in a clean EXN.
  files.<CDROM path>.strings   in-place string overrides in any other disc
                  file (script containers), staged over the pristine copy.
  containers      the sheet injector (tools/patch/inject.py): {"dirs":
                  ["SERIFU", "SPEAKTST"], "only": ["SERIFU/G_APPEAR", ...],
                  "status": [accepted Status values], "dte": "auto" |
                  "build/patch/gen/dte.json" | false, "dte_count": 80}.
                  Every selected container is repacked at its exact size
                  from the translation sheets, the DTE dictionary goes
                  into the string pool and patch_dte_table[], and
                  build/patch/inject.report.json carries the fit report.
  encoding        "ascii" | "fullwidth" | "patch" (tools/patch/textcodec.py:
                  {tokens} -> control bytes, ASCII, Shift-JIS pass-through).

Usage:
    python3 tools/patch/build_patched.py config/patch/english.json
    python3 tools/patch/build_patched.py <profile> --no-iso   # exe/EXN only

Requires the retail clean builds to exist and verify first:
    python3 tools/overlay/build_clean_exn.py <OV> --verify
    python3 tools/build/build_clean_main.py --verify
"""
