RANGE_TABLE = 0x800BA530      # D_800BA530: (sjis_start, glyph_base) pairs
RANGE_TABLE_END = 0x800BA5E4
FONT_MIN_CODE = 0x800BA52C    # D_800BA52C


def sjis_glyph_index(exe: bytes, code: int):
    """pt_sjis_glyph in Python (the retail range table in the exe)."""
    lo_code = struct.unpack_from("<H", exe, file_off(FONT_MIN_CODE))[0]
    if code < lo_code:
        return None
    n = (RANGE_TABLE_END - RANGE_TABLE) // 2
    tab = struct.unpack_from(f"<{n}H", exe, file_off(RANGE_TABLE))
    for i in range(0, n, 2):
        if code < tab[i]:
            return tab[i - 1] + (code - tab[i - 2])
    return None


def sjis_runs(data: bytes, min_chars=2):
    """Shift-JIS double-byte runs inside arbitrary data (data-region scan)."""
    out = []
    i = 0
    n = len(data)
    run = []
    while i + 1 < n:
        b = data[i]
        if textcodec.is_sjis_lead(b) and 0x40 <= data[i + 1] <= 0xFC and data[i + 1] != 0x7F:
            run.append((b << 8) | data[i + 1])
            i += 2
            continue
        if len(run) >= min_chars:
            out.append(run)
        run = []
        i += 1
    if len(run) >= min_chars:
        out.append(run)
    return out


def japanese_left_corpus(profile: dict, report: dict):
    """Every Shift-JIS character that can still reach the renderer: the
    overlay data regions (the EXN strings are not translated yet, except
    the profile's overrides), the main exe's data region, and the container
    rows the injector left in Japanese."""
    from collections import Counter
    cnt = Counter()
    dead = {"EVENT", "GYOZI"}
    for exn in sorted(ASSET_EXN_DIR.glob("*.EXN")):
        if exn.stem in dead:
            continue
        data = exn.read_bytes()
        for run in sjis_runs(data):
            cnt.update(run)
    exe = CLEAN_EXE.read_bytes()
    for run in sjis_runs(exe[file_off(0x800B5A60):file_off(0x800BD250)]):
        cnt.update(run)
    rep_path = ROOT / "build" / "patch" / "inject.report.json"
    if profile.get("containers") and rep_path.exists():
        rep = json.loads(rep_path.read_text())
        for c in rep.get("containers", []):
            for jp in c.get("japanese_left", []):
                for ch in re.sub(r"\{[A-Za-z]+\}", "", jp):
                    try:
                        sj = ch.encode("shift_jis")
                    except UnicodeEncodeError:
                        continue
                    if len(sj) == 2:
                        cnt[(sj[0] << 8) | sj[1]] += 1
    return cnt


def choose_kanji_subset(profile: dict, exe: bytearray, pool_base_no_sub: int,
                        report: dict):
    """Pick the limit L and the subset S that cover the most kanji
    occurrences: lowering the limit from L0 to L frees 18*(L0-L) bytes for
    subset entries of 20 bytes (2-byte code + 18-byte glyph copy), filled
    with the most frequent glyphs >= L.  Returns the blob and the numbers."""
    cnt = japanese_left_corpus(profile, report)
    freq = {}
    for code, n in cnt.items():
        g = sjis_glyph_index(bytes(exe), code)
        if g is not None and g >= 453:        # kanji only (453..3417)
            freq[g] = (freq.get(g, (0, code))[0] + n, code)
    total = sum(v[0] for v in freq.values())
    if total == 0:
        return None
    L0 = (pool_base_no_sub - FONT_BASE) // 18
    if L0 > FONT_GLYPHS:
        return None
    best = None
    for L in range(L0, 452, -25):
        avail = 18 * (L0 - L) - 16
        K = max(0, avail // 20)
        lost = sorted(((v[0], g) for g, v in freq.items() if g >= L), reverse=True)
        kept = sum(v[0] for g, v in freq.items() if g < L)
        cover = kept + sum(f for f, _ in lost[:K])
        if best is None or cover > best[0]:
            best = (cover, L, K, [g for _, g in lost[:K]])
    if best is None:            # the module already reaches the kana glyphs: no room
        return None
    cover, L, K, glyphs = best
    plain = sum(v[0] for g, v in freq.items() if g < L0)
    if K == 0:
        return None
    entries = sorted((freq[g][1], g) for g in glyphs)
    codes = struct.pack(f"<{len(entries)}H", *[c for c, _ in entries])
    codes += b"\0" * ((-len(codes)) % 4)
    blob = bytearray(codes)
    for _, g in entries:
        off = file_off(FONT_BASE + 18 * g)
        blob += exe[off:off + 18]
    blob += b"\0" * ((-len(blob)) % 4)
    sub = {"blob": bytes(blob), "codes_bytes": len(codes), "count": len(entries),
           "limit": L, "coverage_pct": 100.0 * cover / total,
           "plain_pct": 100.0 * plain / total, "occurrences": total,
           "distinct_kanji": len(freq)}
    report["kanji_subset"] = {k: v for k, v in sub.items() if k != "blob"}
    # the Shift-JIS codes the patched renderer can draw (text_sources.py
    # reports the Japanese left on the disc that uses a dropped glyph)
    kept = set(c for c, _ in entries)
    drawable = []
    for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xF0)):
        for trail in range(0x40, 0xFD):
            if trail == 0x7F:
                continue
            code = (lead << 8) | trail
            g = sjis_glyph_index(bytes(exe), code)
            if g is not None and (g < L or code in kept):
                drawable.append(code)
    # the patch's own button icons (text_vwf.c pt_icon_rows, icons12.txt)
    drawable += sorted(int.from_bytes(b, "big") for _, b in textcodec.ICONS.values())
    gen = OUT_GEN_DIR[0] if OUT_GEN_DIR else ROOT / "build" / "patch" / "gen"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "kanji_subset.json").write_text(json.dumps(
        {"limit": L, "subset_codes": sorted(kept), "drawable_codes": drawable}) + "\n")
    return sub


