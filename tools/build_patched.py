def apply_pokes(profile: dict, exe: bytearray, report: dict, pins: SymbolPins,
                module_syms: dict):
    """`main.pokes`: write literal bytes into the file-backed image
    ({"addr" | "symbol", "u8" | "u16" | "u32" | "u32_symbol" | "bytes", "note"})."""
    entries = []
    for pk in profile.get("main", {}).get("pokes", []):
        if "addr" in pk:
            addr = hx(pk["addr"])
        else:
            sym = pk["symbol"]
            addr = module_syms.get(sym)
            if addr is None:
                addr = pins.resolve(sym)
            pins.fail_if_missing(f"poke {sym}")
        if "u8" in pk:
            data = struct.pack("<B", int(pk["u8"]) & 0xFF)
        elif "u16" in pk:
            data = struct.pack("<H", int(pk["u16"]) & 0xFFFF)
        elif "u32" in pk:
            data = struct.pack("<I", hx(pk["u32"]) & 0xFFFFFFFF)
        elif "u32_symbol" in pk:            # the address of a (module) symbol
            v = module_syms.get(pk["u32_symbol"])
            if v is None:
                v = pins.resolve(pk["u32_symbol"])
            if v is None:
                raise SystemExit(f"[patch] poke: symbol {pk['u32_symbol']} not found")
            data = struct.pack("<I", v & 0xFFFFFFFF)
        else:
            data = bytes.fromhex(pk["bytes"])
        lo = file_off(addr)
        if lo < 0x800 or lo + len(data) > len(exe):
            raise SystemExit(f"[patch] poke 0x{addr:08X}: not file-backed "
                             f"(.bss is zero-filled by the loader; poke it at "
                             f"run time instead)")
        old = bytes(exe[lo:lo + len(data)])
        exe[lo:lo + len(data)] = data
        entries.append({"addr": f"0x{addr:08X}", "old": old.hex(),
                        "new": data.hex(), "note": pk.get("note", "")})
        print(f"[patch] poke 0x{addr:08X}: {old.hex()} -> {data.hex()}  "
              f"{pk.get('note', '')}")
    report["pokes"] = entries


def apply_callsites(profile: dict, exe: bytearray, report: dict,
                    pins: SymbolPins, module_syms: dict):
    """`main.callsites`: {"at", "expect", "target"} -- the word at `at` must
    be `jal <expect>` (resolved through the pins); it becomes
    `jal <module target>` (for functions whose head cannot take a
    trampoline, e.g. game_main's hoisted cross-prologue load)."""
    entries = []
    for cs in profile.get("main", {}).get("callsites", []):
        at = hx(cs["at"])
        expect = cs["expect"]
        exp_addr = pins.resolve(expect)
        pins.fail_if_missing(f"callsite {expect}")
        target = module_syms.get(cs["target"])
        if target is None:
            raise SystemExit(f"[patch] callsite {cs['target']}: module does not "
                             f"define it")
        old = struct.unpack_from("<I", exe, file_off(at))[0]
        want = (3 << 26) | ((exp_addr >> 2) & 0x3FFFFFF)
        if old != want:
            raise SystemExit(f"[patch] callsite 0x{at:08X}: word is 0x{old:08X}, "
                             f"not `jal {expect}` (0x{want:08X})")
        new = (3 << 26) | ((target >> 2) & 0x3FFFFFF)
        struct.pack_into("<I", exe, file_off(at), new)
        entries.append({"at": f"0x{at:08X}", "expect": expect,
                        "expect_addr": f"0x{exp_addr:08X}", "target": cs["target"],
                        "target_addr": f"0x{target:08X}", "old_word": f"0x{old:08X}",
                        "new_word": f"0x{new:08X}"})
        print(f"[patch] callsite 0x{at:08X}: jal {expect} -> jal {cs['target']} "
              f"(0x{target:08X})")
    report["callsites"] = entries


def merge_profile(base: dict, extra: dict):
    """deep merge for `include`: dicts merge, lists concatenate, scalars of
    the including profile win"""
    for k, v in extra.items():
        if k == "include":
            continue
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            merge_profile(base[k], v)
        elif isinstance(v, list) and isinstance(base.get(k), list):
            base[k] = base[k] + v
        else:
            base[k] = v
    return base


def load_profile(path: Path) -> dict:
    prof = json.loads(path.read_text())
    if "include" in prof:
        base = load_profile(locate(prof["include"]))
        prof = merge_profile(base, prof)
    return prof


def defined_symbols(objs):
    out = set()
    for o in objs:
        r = subprocess.run([NM, "--defined-only", str(o)], capture_output=True,
                           text=True)
        for line in r.stdout.splitlines():
            parts = line.split()
            if len(parts) == 3:
                out.add(parts[2])
    return out


