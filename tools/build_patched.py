def sha1_file(p: Path) -> str:
    h = hashlib.sha1()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def file_off(addr: int) -> int:
    return addr - TEXT_BASE + FILE_BASE


def hx(v) -> int:
    return int(v, 16) if isinstance(v, str) else int(v)


