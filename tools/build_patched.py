OUT_FILES_DIR = ROOT / "build" / "patch" / "files"
CURRENT_DTE = []     # the run's DTE dictionary (set by main() after the injector)
OUT_GEN_DIR = []     # [out_dir/gen] of the running profile (kanji_subset.json)
# module strings (src/patch/main/patch_text.h PT_C_STR): a retail slot too
# short for its English (a composed string's joiner) holds PT_C_STR + index;
# the text sits in the main string pool and patch_str_table[index] points at
# it.  "{dst}" in the text is PT_C_DST, the splice point of a reordering
# strcat template (text_names.c).  Entries: {"addr", "max_bytes", "text",
# "module": true} in main.strings or overlays.<OV>.strings.
PT_C_STR, PT_C_DST, PT_STR_BASE, PT_STR_COUNT = 0x1D, 0x1A, 0x20, 64
MODULE_STRINGS = []  # encoded texts in index order
MODULE_OFFSETS = []  # their offsets in the string pool


def module_text_bytes(text: str) -> bytes:
    """a module string: plain ASCII without DTE (the renderer expands it
    like a dictionary entry), {br}, and {dst} -> PT_C_DST"""
    enc = bytes([PT_C_DST]).join(textcodec.encode(part, None) for part in text.split("{dst}"))
    if any(b >= 0x80 for b in enc):
        raise SystemExit(f"[patch] module string {text!r}: only ASCII, {{br}} and {{dst}}")
    return enc


def module_string_entries(profile: dict):
    out = [s for s in main_string_entries(profile) if s.get("module")]
    for spec in profile.get("overlays", {}).values():
        out += [s for s in spec.get("strings", []) if s.get("module")]
    return out


def assign_module_strings(profile: dict):
    """index every module string (identical texts share one entry)"""
    MODULE_STRINGS.clear()
    index = {}
    for s in module_string_entries(profile):
        if "addr" not in s or int(s.get("max_bytes", 0)) < 2:
            raise SystemExit(f"[patch] module string {s.get('text')!r}: needs an "
                             f"\"addr\" slot of >= 2 bytes for its reference")
        enc = module_text_bytes(s["text"])
        if enc not in index:
            index[enc] = len(MODULE_STRINGS)
            MODULE_STRINGS.append(enc)
        s["_module_index"] = index[enc]
    if len(MODULE_STRINGS) > PT_STR_COUNT:
        raise SystemExit(f"[patch] {len(MODULE_STRINGS)} module strings > {PT_STR_COUNT}")


def module_ref_bytes(s: dict) -> bytes:
    return bytes([PT_C_STR, PT_STR_BASE + s["_module_index"]])


def encode_text(text: str, encoding: str, dte: bool = False) -> bytes:
    """`dte=True` applies the run's DTE dictionary (only for strings the
    renderer/formatters read; never for name tables that are copied into
    the save file, since a rebuilt dictionary would change the bytes)."""
    if encoding == "ascii":
        return text.encode("ascii")
    if encoding == "patch":
        return textcodec.encode(text, CURRENT_DTE if dte else None)
    if encoding == "fullwidth":
        # ASCII letters/digits/space as full-width Shift-JIS (no code change
        # needed: the retail renderer already has these glyphs)
        out = bytearray()
        for ch in text:
            if ch == " ":
                out += b"\x81\x40"
            elif "0" <= ch <= "9":
                out += (0x824F + ord(ch) - ord("0")).to_bytes(2, "big")
            elif "A" <= ch <= "Z":
                out += (0x8260 + ord(ch) - ord("A")).to_bytes(2, "big")
            elif "a" <= ch <= "z":
                out += (0x8281 + ord(ch) - ord("a")).to_bytes(2, "big")
            else:
                out += ch.encode("shift_jis")
        return bytes(out)
    raise SystemExit(f"[patch] unknown encoding {encoding}")


def overlay_symbol_window(ov_name: str, addr: int):
    """(start, size, name) of the overlay symbol whose window CONTAINS `addr`
    in config/overlay/<OV>.sym (lines `0xADDR:SIZE:name`).  Many windows
    start a few words before the prologue (the absorbed cross-prologue
    head, e.g. BUNKA_SD 0x80133204:828:func_8013320C); callers jal the
    window start, so the trampoline must be written there."""
    sym = DECOMP / "config" / "overlay" / f"{ov_name}.sym"
    for line in sym.read_text().splitlines():
        parts = line.strip().split(":")
        if len(parts) >= 3 and parts[0].lower().startswith("0x"):
            try:
                start, size = int(parts[0], 16), int(parts[1])
            except ValueError:
                continue
            if start <= addr < start + size:
                return start, size, parts[2]
    return None


def apply_overlay_hooks(ov_name: str, spec: dict, payload: bytearray,
                        module_syms: dict, report_entries: list):
    """`overlays.<OV>.hooks`: [{"function", "addr", "target"}] -- write a
    `j <main module function>; nop` trampoline into the overlay function's
    retail window (by ADDRESS; `function` is documentary).  The target is a
    function of the MAIN module (src/patch/main/text_ov_*.c), which is
    always resident, so overlay-side text fixes need no per-EXN placement."""
    for h in spec.get("hooks", []):
        if "addr" not in h:
            raise SystemExit(f"[patch] {ov_name} hook {h.get('function')}: "
                             f"needs an \"addr\" field")
        addr = hx(h["addr"])
        if not (OVERLAY_BASE <= addr < OVERLAY_BASE + EXN_SIZE - 8):
            raise SystemExit(f"[patch] {ov_name} hook 0x{addr:08X}: outside the overlay")
        target = module_syms.get(h["target"])
        if target is None:
            raise SystemExit(f"[patch] {ov_name} hook {h.get('function')}: main "
                             f"module has no {h['target']}")
        win = overlay_symbol_window(ov_name, addr)
        if win is None or win[1] < 8:
            raise SystemExit(f"[patch] {ov_name} hook 0x{addr:08X}: no symbol "
                             f"window of >= 8 bytes covers that address in "
                             f"config/overlay/{ov_name}.sym")
        start, size, symname = win
        if start != addr:
            print(f"[patch] {ov_name} hook {h.get('function')}: window "
                  f"{symname} starts at 0x{start:08X} (absorbed head); "
                  f"trampoline written there")
            addr = start
        off = addr - OVERLAY_BASE
        old = bytes(payload[off:off + 8])
        j_word = (2 << 26) | ((target >> 2) & 0x3FFFFFF)
        struct.pack_into("<II", payload, off, j_word, 0)
        report_entries.append({"function": h.get("function"), "addr": f"0x{addr:08X}",
                               "size": size, "target": h["target"],
                               "target_addr": f"0x{target:08X}",
                               "old_words": old.hex()})
        print(f"[patch] {ov_name} hook {h.get('function')}: 0x{addr:08X} -> "
              f"{h['target']} 0x{target:08X}")


def apply_overlay_strings(ov_name: str, spec: dict, report: dict,
                          module_syms: dict = None, out_root: Path = None):
    clean = CLEAN_EXN_DIR / ov_name / f"{ov_name}.clean.EXN"
    asset = ASSET_EXN_DIR / f"{ov_name}.EXN"
    if not clean.exists():
        if not same_tree():
            raise SystemExit(f"[patch] {ov_name}: {clean} missing; build the "
                             f"clean EXNs in toki1-decomp first ({DECOMP}: "
                             f"make check-exn-all)")
        # a fresh checkout: build the verified base instead of asking for it
        print(f"[patch] {ov_name}: clean EXN missing; building it "
              f"(tools/overlay/build_clean_exn.py {ov_name} --verify)")
        r = subprocess.run([sys.executable, str(ROOT / "tools/overlay/build_clean_exn.py"),
                            ov_name, "--verify"], capture_output=True, text=True, cwd=ROOT)
        if r.returncode != 0 or not clean.exists():
            raise SystemExit(f"[patch] {ov_name}: clean EXN build failed:\n"
                             f"{r.stdout[-800:]}{r.stderr[-800:]}")
    if sha1_file(clean) != sha1_file(asset):
        raise SystemExit(f"[patch] {ov_name}: clean EXN is not byte-perfect; "
                         f"refusing to patch an unverified base")
    data = bytearray(clean.read_bytes())
    if len(data) != EXN_SIZE:
        raise SystemExit(f"[patch] {ov_name}: unexpected EXN size")
    payload = data[:-4]
    out_entries = []
    # relocation pool: strings referenced through a POINTER WORD inside the
    # overlay ("ptr_at": a .data table slot) are placed at the top of the
    # image, right below the checksum trailer, and the slot is rewritten.
    # The top of the image is the safest free space: an overlay's .bss, if
    # any, follows its .data at the low end of the zero tail.
    last_nz = len(payload)
    while last_nz > 0 and payload[last_nz - 1] == 0:
        last_nz -= 1
    pool_entries = [s for s in spec.get("strings", []) if "ptr_at" in s]
    pool = bytearray()
    pool_offsets = []
    for s in pool_entries:
        enc = encode_text(s["text"], s.get("encoding", "patch"), bool(s.get("dte", False)))
        pool_offsets.append(len(pool))
        pool += enc + b"\0"
        pool += b"\0" * ((-len(pool)) % 4)
    pool_base = (len(payload) - 16 - len(pool)) & ~0x3
    if pool and pool_base < last_nz + 256:
        raise SystemExit(f"[patch] {ov_name}: relocation pool ({len(pool)} bytes) "
                         f"does not fit above the image's last data byte "
                         f"0x{OVERLAY_BASE + last_nz:08X}")
    if pool:
        payload[pool_base:pool_base + len(pool)] = pool
        for s, off in zip(pool_entries, pool_offsets):
            ptr_at = hx(s["ptr_at"])
            old = struct.unpack_from("<I", payload, ptr_at - OVERLAY_BASE)[0]
            if not (OVERLAY_BASE <= old < OVERLAY_BASE + EXN_SIZE):
                raise SystemExit(f"[patch] {ov_name} ptr_at 0x{ptr_at:08X} holds "
                                 f"0x{old:08X}, not an overlay pointer")
            new = OVERLAY_BASE + pool_base + off
            struct.pack_into("<I", payload, ptr_at - OVERLAY_BASE, new)
            out_entries.append({"ptr_at": f"0x{ptr_at:08X}", "old_target": f"0x{old:08X}",
                                "new_target": f"0x{new:08X}", "text": s["text"],
                                "dte": bool(s.get("dte", False))})
        print(f"[patch] {ov_name}: {len(pool_entries)} strings relocated into "
              f"0x{OVERLAY_BASE + pool_base:08X}.. ({len(pool)} bytes)")
    for s in spec.get("strings", []):
        if "ptr_at" in s:
            continue
        addr = hx(s["addr"])
        max_bytes = int(s["max_bytes"])
        if s.get("module"):
            enc = module_ref_bytes(s)
        else:
            enc = encode_text(s["text"], s.get("encoding", "ascii"), bool(s.get("dte", False)))
        if len(enc) > max_bytes:
            raise SystemExit(f"[patch] {ov_name} 0x{addr:08X}: '{s['text']}' "
                             f"is {len(enc)} bytes, budget {max_bytes}")
        off = addr - OVERLAY_BASE
        old = bytes(payload[off:off + max_bytes + 1])
        if old[max_bytes] != 0:
            raise SystemExit(f"[patch] {ov_name} 0x{addr:08X}: byte after the "
                             f"budget is not NUL -- budget wrong?")
        payload[off:off + max_bytes + 1] = enc + b"\0" * (max_bytes + 1 - len(enc))
        out_entries.append({"addr": f"0x{addr:08X}", "max_bytes": max_bytes,
                            "bytes": len(enc), "text": s["text"],
                            "encoding": s.get("encoding", "ascii"),
                            "old_sha1": hashlib.sha1(old).hexdigest()})
        print(f"[patch] {ov_name}: 0x{addr:08X} <- {s['text']!r} "
              f"({len(enc)}/{max_bytes} bytes)")
    hook_entries = []
    if spec.get("hooks"):
        apply_overlay_hooks(ov_name, spec, payload, module_syms or {}, hook_entries)
    # callsites: {"at", "expect" (the retail callee's address), "target"
    # (a main-module function)} -- the word at `at` must be `jal expect`;
    # it becomes `jal target` (the BIOS string thunks have no window for
    # a trampoline, and a hook on them would catch every caller)
    for cs in spec.get("callsites", []):
        at, exp = hx(cs["at"]), hx(cs["expect"])
        target = (module_syms or {}).get(cs["target"])
        if target is None:
            raise SystemExit(f"[patch] {ov_name} callsite {cs['target']}: the main module "
                             f"does not define it")
        old_w = struct.unpack_from("<I", payload, at - OVERLAY_BASE)[0]
        want = (3 << 26) | ((exp >> 2) & 0x3FFFFFF)
        if old_w != want:
            raise SystemExit(f"[patch] {ov_name} callsite 0x{at:08X}: word is 0x{old_w:08X}, "
                             f"not jal 0x{exp:08X}")
        new_w = (3 << 26) | ((target >> 2) & 0x3FFFFFF)
        struct.pack_into("<I", payload, at - OVERLAY_BASE, new_w)
        hook_entries.append({"callsite": f"0x{at:08X}", "expect": f"0x{exp:08X}",
                             "target": cs["target"], "target_addr": f"0x{target:08X}"})
        print(f"[patch] {ov_name} callsite 0x{at:08X}: jal 0x{exp:08X} -> jal "
              f"{cs['target']} (0x{target:08X})")
    out_dir = (out_root or (ROOT / "build" / "patch")) / "EXEDIR"
    out_dir.mkdir(parents=True, exist_ok=True)
    tmp_bin = out_dir / f"{ov_name}.patched.bin"
    out_exn = out_dir / f"{ov_name}.EXN"
    tmp_bin.write_bytes(bytes(payload))
    if not add_exn_checksum(tmp_bin, out_exn):
        raise SystemExit(f"[patch] {ov_name}: checksum step failed")
    tmp_bin.unlink()
    report["overlays"][ov_name] = {"out": str(out_exn.relative_to(ROOT)),
                                   "sha1": sha1_file(out_exn),
                                   "strings": out_entries,
                                   "hooks": hook_entries}
    return out_exn


def seal_files(exe_path: Path, exns: dict, files: dict, report: dict):
    """Before the disc is assembled, hold every changed file to the loader
    contracts (tools/patch/verify_disc.py loader_contracts):

      * a block checksum (big-endian u16 byte sum, block_checksum_check)
        that is valid in the retail file is re-stamped -- the text
        containers kept their retail sums after repacking until 2026-10-09
        (no retail loader verifies a container today, but every one of them
        carries a valid sum, and OMIKUJI.BIN proved that a stale sum on a
        checked file hangs the game);
      * the 0x1012 read footers stay, the EXN trailer is right, the size is
        unchanged and the PS-X EXE header is untouched.
    Any violation left after re-stamping fails the build."""
    import verify_disc
    extracted = DECOMP / "assets" / "extracted_iso"
    out = {"restamped": {}, "checked": 0}
    bad = []
    for rel, p in sorted(files.items()):
        retail = (extracted / rel).read_bytes()
        data = bytearray(Path(p).read_bytes())
        done = verify_disc.restamp_block_sums(retail, data)
        if done:
            Path(p).write_bytes(bytes(data))
            out["restamped"][rel] = [f"+0x{a:x}..+0x{b:x}" for a, b in done]
        bad += [f"{rel}: {x}" for x in
                verify_disc.loader_contracts(retail, bytes(data), rel.split("/")[-1])]
        out["checked"] += 1
    for ov, p in sorted(exns.items()):
        retail = (ASSET_EXN_DIR / f"{ov}.EXN").read_bytes()
        bad += [f"{ov}.EXN: {x}" for x in
                verify_disc.loader_contracts(retail, Path(p).read_bytes(), f"{ov}.EXN")]
        out["checked"] += 1
    bad += [f"PSX.EXE: {x}" for x in
            verify_disc.loader_contracts(RETAIL_EXE.read_bytes(),
                                         exe_path.read_bytes(), "PSX.EXE")]
    out["checked"] += 1
    report["integrity"] = out
    if bad:
        for b in bad[:20]:
            print(f"[patch] integrity FAIL: {b}")
        raise SystemExit(f"[patch] {len(bad)} loader-contract violations")
    print(f"[patch] integrity: {out['checked']} changed files hold the loader "
          f"contracts; block checksums re-stamped in {len(out['restamped'])}")


